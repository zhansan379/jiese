def classify_topic(*texts: str) -> str:
    """多段文本（规范表述 + 成员断言）→ 主题。空文本归「其他」。"""
    joined = " ".join(t for t in texts if t)
    if not joined:
        return TOPIC_OTHER
    best, best_score = TOPIC_OTHER, 0
    for topic, keywords in TOPIC_RULES:
        score = sum(1 for kw in keywords if kw in joined)
        if score > best_score:
            best, best_score = topic, score
    return best
